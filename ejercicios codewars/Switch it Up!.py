def switch_it_up(n):
    
    number = ""
    
    match n:
        case 0: number = "Zero"
        case 1: number = "One" 
        case 2: number = "Two"
        case 3: number = "Three"
        case 4: number = "Four"
        case 5: number = "Five"
        case 6: number = "Six"
        case 7: number = "Seven"
        case 8: number = "Eight"
        case 9: number = "Nine"
    return number 